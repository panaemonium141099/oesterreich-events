/**
 * Fallback: find nearest district center within a Bundesland.
 */
function _nearestDistrictCenter(lat: number, lng: number, bundeslandId: string): string | null {
  const districts = DISTRICTS_BY_BUNDESLAND[bundeslandId as BundeslandId];
  if (!districts || districts.length === 0) return null;

  let nearest = districts[0];
  let minDist = _haversineApprox(lat, lng, nearest.center[0], nearest.center[1]);

  for (let i = 1; i < districts.length; i++) {
    const d = _haversineApprox(lat, lng, districts[i].center[0], districts[i].center[1]);
    if (d < minDist) {
      minDist = d;
      nearest = districts[i];
    }
  }

  return nearest.name;
}

/**
 * Quick squared-distance approximation (good enough for nearest-center within a Bundesland).
 */
function _haversineApprox(lat1: number, lng1: number, lat2: number, lng2: number): number {
  const dLat = lat2 - lat1;
  const dLng = (lng2 - lng1) * Math.cos(((lat1 + lat2) / 2) * (Math.PI / 180));
  return dLat * dLat + dLng * dLng;
}
