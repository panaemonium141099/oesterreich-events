/**
 * Get all districts for a given Bundesland.
 */
export function getDistrictsByBundesland(bundeslandId: string): DistrictInfoAT[] {
  return DISTRICTS_BY_BUNDESLAND[bundeslandId as BundeslandId] || [];
}

/**
 * Look up Bundesland and district by Austrian postal code.
 */
export function getDistrictByPostalCodeAT(postalCode: string): { bundesland: string; district: string } | null {
  // Wien: simple mapping 1XXX -> Bezirk number
  if (/^1\d{2}0$/.test(postalCode)) {
    const bezirkNum = parseInt(postalCode.substring(1, 3), 10);
    if (bezirkNum >= 1 && bezirkNum <= 23) {
      const wienDistricts = DISTRICTS_BY_BUNDESLAND.wien;
      const district = wienDistricts.find(d => d.postalCodes.includes(postalCode));
      if (district) {
        return { bundesland: 'wien', district: district.name };
      }
    }
  }

  // Search all Bundesländer
  for (const [bundeslandId, districts] of Object.entries(DISTRICTS_BY_BUNDESLAND)) {
    for (const district of districts) {
      if (district.postalCodes.includes(postalCode)) {
        return { bundesland: bundeslandId, district: district.name };
      }
    }
  }

  // Try prefix-based matching (first 2 digits)
  const prefix2 = postalCode.substring(0, 2);
  for (const [bundeslandId, districts] of Object.entries(DISTRICTS_BY_BUNDESLAND)) {
    for (const district of districts) {
      if (district.postalCodes.some(plz => plz.substring(0, 2) === prefix2)) {
        return { bundesland: bundeslandId, district: district.name };
      }
    }
  }

  return null;
}

/**
 * Look up district by location name. Optionally restrict search to a specific Bundesland.
 */
export function getDistrictByLocationAT(locationName: string, bundeslandId?: string): string | null {
  if (!locationName) return null;
  const loc = locationName.toLowerCase().trim();

  for (const [keyword, mapping] of Object.entries(LOCATION_DISTRICT_MAP_AT)) {
    if (bundeslandId && mapping.bundesland !== bundeslandId) continue;
    if (loc.includes(keyword)) {
      return mapping.district;
    }
  }

  return null;
}

/**
 * Approximate district lookup by coordinates within a Bundesland.
 * Uses rough latitude/longitude zones — not a precise GIS lookup.
 */
export function getDistrictByCoordsAT(lat: number, lng: number, bundeslandId: string): string | null {
  switch (bundeslandId) {
    case 'burgenland':
      return _burgenlandByCoords(lat, lng);
    case 'wien':
      return _wienByCoords(lat, lng);
    case 'niederoesterreich':
      return _niederoesterreichByCoords(lat, lng);
    case 'oberoesterreich':
      return _oberoesterreichByCoords(lat, lng);
    case 'salzburg':
      return _salzburgByCoords(lat, lng);
    case 'steiermark':
      return _steiermarkByCoords(lat, lng);
    case 'kaernten':
      return _kaerntenByCoords(lat, lng);
    case 'tirol':
      return _tirolByCoords(lat, lng);
    case 'vorarlberg':
      return _vorarlbergByCoords(lat, lng);
    default:
      return _nearestDistrictCenter(lat, lng, bundeslandId);
  }
}

